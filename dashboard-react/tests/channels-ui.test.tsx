import { fireEvent, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { expect, it, vi } from 'vitest'
import { ChannelsPage } from '../src/pages/ChannelsPage'
import { channel, fail, health, list, mapping, renderPage, requests, respond } from './support'

it('creates and edits channels, reports failed actions, switches status, resets health, and confirms deletion', async () => {
  const user = userEvent.setup(); const confirm = vi.spyOn(window, 'confirm').mockReturnValue(true)
  renderPage(<ChannelsPage />)
  await screen.findByText('Primary')
  await user.click(screen.getByRole('button', { name: '刷新' }))
  await user.click(screen.getByRole('button', { name: '新建渠道' }))
  await user.type(screen.getByLabelText('渠道名称'), 'New'); await user.type(screen.getByLabelText('Base URL'), 'https://new.example/v1')
  fireEvent.submit(screen.getByRole('dialog'))
  expect(await screen.findByRole('alert')).toHaveTextContent('新建渠道必须填写上游 API Key')
  await user.type(screen.getByLabelText('上游 API Key'), 'test-placeholder')
  await user.type(screen.getByLabelText('余额'), '1.000000')
  await user.click(screen.getByRole('button', { name: '创建' }))
  await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
  expect(requests.find(r => r.method === 'POST' && r.path === '/admin/channels')?.body).toMatchObject({ name: 'New', api_key: 'test-placeholder', balance: '1.000000' })
  await user.click(screen.getByRole('button', { name: '编辑' }))
  await user.clear(screen.getByLabelText('渠道名称')); await user.type(screen.getByLabelText('渠道名称'), 'Edited')
  await user.click(screen.getByRole('button', { name: '保存' }))
  await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
  expect(requests.find(r => r.method === 'PUT' && r.path === '/admin/channels/2')?.body).toMatchObject({ name: 'Edited' })
  respond('/admin/channels/2/status', fail('toggle failed'), 'PUT')
  await user.click(screen.getByRole('button', { name: '切换状态' })); await screen.findByText('toggle failed')
  respond('/admin/channels/2/status', channel, 'PUT')
  await user.click(screen.getByRole('button', { name: '切换状态' }))
  await user.click(screen.getByRole('button', { name: '解除熔断' }))
  confirm.mockReturnValueOnce(false); await user.click(screen.getByRole('button', { name: '删除' }))
  expect(requests.some(r => r.method === 'DELETE' && r.path === '/admin/channels/2')).toBe(false)
  respond('/admin/channels', list([])); await user.click(screen.getByRole('button', { name: '删除' }))
  await screen.findByText('暂无渠道')
  await user.click(screen.getByRole('button', { name: '新建渠道' })); await user.click(screen.getByRole('button', { name: '取消' }))
})


it('loads remote models, maps individually/all, catches mapping errors, and edits/deletes manual mappings', async () => {
  const user = userEvent.setup(); vi.spyOn(window, 'confirm').mockReturnValue(true)
  renderPage(<ChannelsPage />); await screen.findByText('Primary')
  await user.click(screen.getByRole('button', { name: '模型映射' }))
  await screen.findByText('gpt-real')
  respond('/admin/channels/2/remote-models', { ok: false, error: 'remote unavailable' }, 'POST')
  await user.click(screen.getByRole('button', { name: '拉取远端模型' })); await screen.findByText('remote unavailable')
  respond('/admin/channels/2/remote-models', { ok: true, models: [{ id: 'gpt-new' }, { id: 'gpt-other' }] }, 'POST')
  await user.click(screen.getByRole('button', { name: '拉取远端模型' })); await screen.findByText('gpt-new')
  respond('/admin/channels/2/models', fail('mapping unavailable'), 'POST')
  await user.click(screen.getByRole('button', { name: /gpt-new：gpt-new/ })); await screen.findByText('mapping unavailable')
  respond('/admin/channels/2/models', mapping, 'POST')
  await user.click(screen.getByRole('button', { name: '一键全部映射' }))
  await waitFor(() => expect(requests.filter(r => r.method === 'POST' && r.path === '/admin/channels/2/models')).toHaveLength(3))
  await user.click(screen.getByRole('button', { name: '手动添加映射' }))
  await user.type(screen.getByLabelText('对外模型名'), 'gpt'); await user.type(screen.getByLabelText('上游模型名'), 'gpt-real')
  await user.click(screen.getByRole('button', { name: '保存' })); await screen.findByText('同一渠道已存在该对外模型名')
  await user.clear(screen.getByLabelText('对外模型名')); await user.type(screen.getByLabelText('对外模型名'), 'new-alias')
  await user.click(screen.getByRole('button', { name: '保存' }))
  await waitFor(() => expect(screen.getAllByRole('dialog')).toHaveLength(1))
  await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: '编辑' }))
  await user.clear(screen.getByLabelText('对外模型名')); await user.type(screen.getByLabelText('对外模型名'), 'edited-alias')
  await user.click(screen.getByRole('button', { name: '保存' }))
  await waitFor(() => expect(screen.getAllByRole('dialog')).toHaveLength(1))
  expect(requests.find(r => r.method === 'PUT' && r.path === '/admin/channels/2/models/3')?.body).toEqual({ model_name: 'edited-alias', enabled: true })
  await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: '删除' }))
  await waitFor(() => expect(requests.some(r => r.method === 'DELETE' && r.path === '/admin/channels/2/models/3')).toBe(true))
  await user.click(screen.getByRole('button', { name: '手动添加映射' }))
  await user.click(within(screen.getAllByRole('dialog')[1]).getByRole('button', { name: '取消' }))
  await user.click(screen.getByRole('button', { name: '取消' }))
})


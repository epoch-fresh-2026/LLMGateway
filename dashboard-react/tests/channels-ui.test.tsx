it('skips blank remote IDs and rejects edits that collide with an existing public model', async () => {
  const user = userEvent.setup()
  respond('/admin/channels/2/models', list([mapping, { ...mapping, id: 9, model_name: 'existing' }]))
  respond('/admin/channels/2/remote-models', { ok: true, models: [{ id: '' }] }, 'POST')
  renderPage(<ChannelsPage />); await screen.findByText('Primary')
  await user.click(screen.getByRole('button', { name: '模型映射' }))
  await screen.findByText('existing')
  await user.click(screen.getByRole('button', { name: '拉取远端模型' }))
  await waitFor(() => expect(screen.getByRole('button', { name: '一键全部映射' })).not.toBeDisabled())
  await user.click(screen.getByRole('button', { name: '一键全部映射' }))
  expect(requests.some(r => r.method === 'POST' && r.path === '/admin/channels/2/models')).toBe(false)
  await user.click(within(screen.getByRole('dialog')).getAllByRole('button', { name: '编辑' })[0])
  await user.clear(screen.getByLabelText('对外模型名')); await user.type(screen.getByLabelText('对外模型名'), 'existing')
  await user.click(screen.getByRole('button', { name: '保存' }))
  await screen.findByText('同一渠道已存在该对外模型名')
  expect(requests.some(r => r.method === 'PUT' && r.path === '/admin/channels/2/models/3')).toBe(false)
})

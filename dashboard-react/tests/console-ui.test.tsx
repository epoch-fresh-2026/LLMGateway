it('creates pricing from a channel mapping, changes selectors, and preserves JSON DELETE', async () => {
  const user = userEvent.setup()
  respond('/admin/channels', list([channel, { ...channel, id: 9, name: 'Secondary' }]))
  respond('/admin/channels/9/models', list([{ ...mapping, upstream_model: 'model-nine' }, { ...mapping, id: 8, upstream_model: 'model-eight' }]))
  renderPage(<PricingPage />)
  await screen.findByText('gpt-real')
  await user.click(screen.getByRole('button', { name: '刷新' }))
  await user.click(screen.getByRole('button', { name: '新建' }))
  await user.selectOptions(screen.getByLabelText('渠道'), '9')
  await screen.findByRole('option', { name: 'model-eight' })
  await user.selectOptions(screen.getByLabelText('上游模型'), 'model-eight')
  await user.type(screen.getByLabelText('输入单价 / 1M'), '0.123456'); await user.type(screen.getByLabelText('输出单价 / 1M'), '1.000000')
  await user.type(screen.getByLabelText('缓存输入单价 / 1M（可选）'), '0.010000')
  await user.click(screen.getByRole('button', { name: '创建' }))
  await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
  expect(requests.find(r => r.method === 'POST' && r.path === '/admin/pricing')?.body).toMatchObject({ channel_id: 9, upstream_model: 'model-eight', cached_input_price_per_1m: '0.010000' })
  await user.click(screen.getByRole('button', { name: '删除' }))
  await waitFor(() => expect(requests.some(r => r.method === 'DELETE' && r.path === '/admin/pricing')).toBe(true))
  expect(requests.find(r => r.method === 'DELETE' && r.path === '/admin/pricing')?.body).toEqual({ channel_id: 2, upstream_model: 'gpt-real' })
  await user.click(screen.getByRole('button', { name: '新建' })); await user.click(screen.getByRole('button', { name: '取消' }))
})

it.each(['channels', 'mappings'])('rejects pricing without %s', async kind => {
  respond('/admin/pricing', list([]))
  if (kind === 'channels') respond('/admin/channels', list([]))
  else respond('/admin/channels/2/models', list([]))
  renderPage(<PricingPage />)
  await waitFor(() => expect(requests.some(r => r.path === '/admin/channels')).toBe(true))
  await userEvent.click(screen.getByRole('button', { name: '新建' }))
  const dialog = screen.getByRole('dialog')
  await userEvent.type(screen.getByLabelText('输入单价 / 1M'), '1'); await userEvent.type(screen.getByLabelText('输出单价 / 1M'), '2')
  fireEvent.submit(dialog)
  expect(await screen.findByText(kind === 'channels' ? '请先创建渠道并配置模型映射' : '该渠道没有可定价的上游模型，请先配置模型映射')).toBeInTheDocument()
})
